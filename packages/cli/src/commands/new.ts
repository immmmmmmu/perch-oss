export function buildDeploymentMd(): string {
  return `# Deployment and Scheduled Rebuilds

perch is a static profile generator. It fetches RSS / Atom / JSON Feed sources during \`perch build\` and writes the result to \`dist/\`.

RSS updates are not reflected until a new build runs.

## Recommended Model

Use a scheduled job to rebuild and redeploy the site.

Typical flow:

\`\`\`text
schedule or manual trigger
  -> perch build
  -> publish dist/
\`\`\`

## GitHub Actions

This project includes \`.github/workflows/perch-build.yml\` as a starting point.

The workflow:

- runs on push
- runs on a schedule
- runs manually via workflow dispatch
- executes \`pnpm build\`
- uploads \`dist/\` as a deployable artifact

If you publish to GitHub Pages, add the official Pages deploy step after the artifact upload.

If you publish to Cloudflare Pages, replace the artifact upload step with:

\`\`\`bash
npx wrangler pages deploy dist --project-name <your-cloudflare-pages-project>
\`\`\`

Set \`CLOUDFLARE_API_TOKEN\` and \`CLOUDFLARE_ACCOUNT_ID\` as repository secrets before enabling Cloudflare deploys.

## Server Cron

On a VPS or another always-on machine, run:

\`\`\`cron
0 * * * * cd /path/to/profile && pnpm build && rsync -a dist/ /var/www/profile/
\`\`\`

Hourly is a good default. Daily is enough if your feeds update rarely.

## Manual Publish

For occasional updates:

\`\`\`bash
pnpm build
# then upload dist/ to your host
\`\`\`

## Files

- Edit \`perch.config.yaml\` and \`public/\`.
- Publish \`dist/\`.
- Do not edit \`dist/\` directly.
- Do not commit \`.perch/\`; it is local cache data.
`;
}

export function buildGithubWorkflowYaml(): string {
  return `name: Build perch profile

on:
  push:
    branches: [main]
  workflow_dispatch:
  schedule:
    # Rebuild hourly so RSS updates are reflected in the published page.
    - cron: '0 * * * *'

permissions:
  contents: read

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v6

      - name: Setup pnpm
        uses: pnpm/action-setup@v6
        with:
          version: 9.15.4

      - name: Setup Node
        uses: actions/setup-node@v6
        with:
          node-version: 22
          cache: pnpm

      - name: Install dependencies
        run: pnpm install --frozen-lockfile

      - name: Run perch build
        run: pnpm build

      - name: Upload dist artifact
        uses: actions/upload-artifact@v4
        with:
          name: perch-dist
          path: dist/
`;
}

