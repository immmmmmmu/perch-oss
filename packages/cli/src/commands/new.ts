async function directoryExists(dir: string): Promise<boolean> {
  try {
    await access(dir);
    return true;
  } catch {
    return false;
  }
}

export async function promptProjectParams(defaults: ProjectParams): Promise<ProjectParams> {
  p.intro('Create a new perch profile page');

  const responses = await p.group(
    {
      name: () =>
        p.text({ message: 'Display name', placeholder: 'My Name', defaultValue: defaults.name }),
      bio: () =>
        p.text({
          message: 'Short bio',
          placeholder: 'Welcome to my profile page.',
          defaultValue: defaults.bio,
        }),
      locale: () =>
        p.select({
          message: 'Default locale',
          options: [
            { value: 'ja', label: 'Japanese (ja)' },
            { value: 'en', label: 'English (en)' },
          ],
          initialValue: 'ja',
        }),
      theme: () =>
        p.select({
          message: 'Theme',
          options: [
            { value: 'editorial', label: 'Editorial — writing, expertise, and trust' },
            { value: 'minimal', label: 'Minimal — lightweight reading-first page' },
            { value: 'grid', label: 'Grid — media-rich post gallery' },
            { value: 'card', label: 'Card — social bio links and latest posts' },
            { value: 'timeline', label: 'Timeline — public activity log' },
          ],
          initialValue: 'editorial',
        }),
    },
    {
      onCancel: () => {
        p.cancel('Setup cancelled.');
        process.exit(0);
      },
    },
  );

  p.outro('Creating project...');

  return {
    name: responses.name,
    bio: responses.bio,
    locale: responses.locale,
    theme: responses.theme,
  };
}

export async function runNew(opts: NewOptions): Promise<void> {
  const exists = await directoryExists(opts.projectDir);
  if (exists) {
    throw new Error(`Directory already exists: ${opts.projectDir}`);
  }

  const defaultParams: ProjectParams = {
    name: opts.name ?? 'My Name',
    bio: 'Welcome to my profile page.',
    locale: opts.locale ?? 'ja',
    theme: opts.theme ?? 'editorial',
  };

  const params = opts.defaults ? defaultParams : await promptProjectParams(defaultParams);

  await mkdir(opts.projectDir, { recursive: true });
  await mkdir(join(opts.projectDir, 'public'), { recursive: true });
  await mkdir(join(opts.projectDir, 'docs'), { recursive: true });
  await mkdir(join(opts.projectDir, 'posts'), { recursive: true });
  await mkdir(join(opts.projectDir, 'assets'), { recursive: true });
  await mkdir(join(opts.projectDir, '.github', 'workflows'), { recursive: true });

  const configYaml = buildConfigYaml(params);
  await writeFile(join(opts.projectDir, 'package.json'), buildPackageJson(), 'utf8');
  await writeFile(join(opts.projectDir, 'perch.config.yaml'), configYaml, 'utf8');
  await writeFile(join(opts.projectDir, 'profile.md'), buildProfileMd(params), 'utf8');
  await writeFile(join(opts.projectDir, 'AGENTS.md'), buildAgentsMd(), 'utf8');
  await writeFile(join(opts.projectDir, 'README.md'), buildReadmeMd(params), 'utf8');
  await writeFile(join(opts.projectDir, 'docs', 'deployment.md'), buildDeploymentMd(), 'utf8');
  await writeFile(
    join(opts.projectDir, '.github', 'workflows', 'perch-build.yml'),
    buildGithubWorkflowYaml(),
    'utf8',
  );

  await writeFile(join(opts.projectDir, 'public', 'og.svg'), buildOgSvg(params.name), 'utf8');
  await writeFile(
    join(opts.projectDir, 'public', 'favicon.svg'),
    buildFaviconSvg(params.name),
    'utf8',
  );

  await writeFile(
    join(opts.projectDir, 'posts', '2026-05-12-hello.md'),
    buildPostsHelloMd(),
    'utf8',
  );

  const gitignore = `dist/\n.perch/\nnode_modules/\n`;
  await writeFile(join(opts.projectDir, '.gitignore'), gitignore, 'utf8');
}
