import { mkdir, writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';

import * as p from '@clack/prompts';

import cliPackage from '../../package.json' with { type: 'json' };

export interface NewOptions {
  readonly projectDir: string;
  readonly defaults: boolean;
  readonly name?: string;
  readonly locale?: string;
  readonly theme?: string;
}

export interface ProjectParams {
  readonly name: string;
  readonly bio: string;
  readonly locale: string;
  readonly theme: string;
}

export function buildConfigYaml(params: ProjectParams): string {
  return `# EDIT THIS FILE
# This is the main input for your self-hosted perch profile.
# Most users only need to update this file and replace files in ./public/.

profile:
  # Required: the name shown at the top of the page.
  name: "${params.name}"

  # Short profile text. Keep it concise; the Editorial theme treats this as
  # a fallback when profile.md is not present.
  bio: "${params.bio}"

  # Long profile body. Markdown formatting is rendered by supported themes.
  markdown: "./profile.md"

  # Optional avatar. Put your image at public/avatar.png and uncomment this.
  # avatarUrl: "./public/avatar.png"

  # Primary links shown near your profile.
  links: []
  # - label: "GitHub"
  #   href: "https://github.com/yourname"
  #   description: "Code, OSS projects, and experiments."
  # - label: "Newsletter"
  #   href: "https://example.com/newsletter"
  #   description: "Monthly notes and essays."

site:
  # Social preview metadata. Replace these before publishing.
  title: "${params.name}"
  description: "Profile of ${params.name}."
  # url: "https://example.com" # canonical URL of this page
  ogImage: "./public/og.svg"
  favicon: "./public/favicon.svg"
  # twitterHandle: "@yourhandle"

# ja or en.
locale: ${params.locale}

# editorial is the recommended default. Other bundled themes:
# minimal, grid, card, timeline.
theme: ${params.theme}

# Replace this with your RSS / Atom / JSON Feed URLs.
feeds: []
  # - url: "https://your-blog.example/feed.xml"
  #   name: "My Blog"
  # - url: "https://zenn.dev/yourname/feed"
  #   name: "Zenn"
  # - url: "https://www.youtube.com/@yourchannel"
  #   name: "YouTube"

# Posts: markdown files in ./posts with frontmatter will be published as HTML.
posts:
  enabled: true
  dir: ./posts
  assetsDir: ./assets
  perPage: 10
  showInTimeline: true
`;
}

